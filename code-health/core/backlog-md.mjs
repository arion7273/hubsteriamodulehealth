import fs from 'node:fs/promises';

/**
 * @param {import('./types.mjs').AuditReport} report
 * @param {string} backlogPath
 */
export async function writeBacklogMarkdown(report, backlogPath) {
  const lines = [];
  lines.push('# Code Health Backlog');
  lines.push('');
  lines.push('Generated by `npm run health:audit`. **Do not edit IDs** — Prompt 2 uses them for execution tracking.');
  lines.push('');
  lines.push('## Run metadata');
  lines.push('');
  lines.push(`| Field | Value |`);
  lines.push(`| --- | --- |`);
  lines.push(`| Repository | \`${report.meta.repository}\` |`);
  lines.push(`| Branch | \`${report.meta.branch}\` |`);
  lines.push(`| Commit | \`${report.meta.commit}\` |`);
  lines.push(`| Dirty working tree | ${report.meta.dirtyWorkingTree ? 'yes' : 'no'} |`);
  lines.push(`| Scan time (UTC) | ${report.meta.scanTimeIso} |`);
  lines.push(`| Scope | ${report.meta.scopeLabel} |`);
  lines.push(`| jscpd | ${report.meta.toolVersions.jscpd} |`);
  lines.push(`| knip | ${report.meta.toolVersions.knip} |`);
  lines.push(`| Report ID | \`${report.reportId}\` |`);
  lines.push('');
  lines.push('## Scanner status');
  lines.push('');
  for (const s of report.scanners) {
    const note = s.error ?? s.skipReason ?? '';
    lines.push(`- **${s.name}**: \`${s.status}\`${note ? ` — ${note}` : ''}`);
  }
  lines.push('');
  lines.push('## Findings');
  lines.push('');

  for (const f of report.findings) {
    lines.push(`### ${f.id}`);
    lines.push('');
    lines.push(`| | |`);
    lines.push(`| --- | --- |`);
    lines.push(`| Category | ${f.category} |`);
    lines.push(`| Priority | ${f.priority} |`);
    lines.push(`| Confidence | ${f.confidence} |`);
    lines.push(`| Cleanup risk | ${f.cleanupRisk} |`);
    lines.push(`| Status | ${f.status}${f.statusReason ? ` (${f.statusReason})` : ''} |`);
    lines.push('');
    lines.push('**Locations**');
    for (const loc of f.locations) {
      lines.push(`- \`${loc.file}\`${loc.line ? `:${loc.line}${loc.endLine ? `-${loc.endLine}` : ''}` : ''}`);
    }
    lines.push('');
    lines.push('**Evidence**');
    lines.push('```json');
    lines.push(JSON.stringify(f.evidence, null, 2));
    lines.push('```');
    lines.push('');
    lines.push(`**Why it matters:** ${f.whyItMatters}`);
    lines.push('');
    lines.push(`**Proposed change:** ${f.proposedChange}`);
    lines.push('');
    lines.push(`**Affected workflows:** ${f.affectedWorkflows.join(', ')}`);
    lines.push('');
    lines.push(`**Verification required:** ${f.verificationRequired.join('; ')}`);
    lines.push('');
    lines.push('---');
    lines.push('');
  }

  if (report.findings.length === 0) {
    lines.push('_No findings from completed scanners._');
    lines.push('');
  }

  await fs.writeFile(backlogPath, lines.join('\n'), 'utf8');
}
